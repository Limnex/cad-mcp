def mode(name):
    short = name.removeprefix("cad_")
    if short in NO_BACKEND:
        return "无需 CAD 后端（文件/模型/缓存）"
    if short in DXF_ONLY:
        return "仅 dxf"
    if short in ACAD_ONLY:
        return "仅 acad"
    if short == "apply_dwt_profile":
        return "acad 正式应用；两模式可预览"
    return "dxf / acad；以能力说明为准"


def clean_cell(value):
    return str(value).replace("|", "&#124;").replace("\n", "<br>")


def parameter_schema(tool):
    schema = tool.parameters
    params = schema.get("properties", {}).get("params", {})
    if "$ref" in params:
        return schema["$defs"][params["$ref"].split("/")[-1]]
    return params


def returned_fields(fn):
    """Report literal outer envelope keys only, never invent an output schema."""
    tree = ast.parse(textwrap.dedent(inspect.getsource(inspect.unwrap(fn))))
    keys = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "_ok":
            for arg in node.args:
                if isinstance(arg, ast.Dict):
                    keys.update(k.value for k in arg.keys if isinstance(k, ast.Constant) and isinstance(k.value, str))
    return sorted(keys)


def render(server):
    tools = server._FULL_TOOL_REGISTRY
    lines = ["# 完整工具参考", "", "<!-- Generated by tools/generate_tool_reference.py; edit runtime descriptions or generator. -->", "",
        f"本表对应仓库源码的 {len(tools)} 个原始 `cad_*` 工具；版本号相同不证明已安装服务与源码一致。",
        "普通模式调用形如 `工具名({\"params\":{...}})`；空参数工具也传空的 `params` 对象。",
        "网关模式先 `cad_gateway_list` / `cad_gateway_describe`，再用 `cad_gateway_call` 转发原始工具。三个网关入口不计入原始工具数量。", "",
        "参数表来自运行时 inputSchema，包含必填性、类型、默认值和范围。嵌套对象、联合类型、枚举及完整约束见[完整参数结构](tool-schemas.json)。",
        "`null` 是显式空值；允许 null 不等于字段可省略。表中的“未设默认值”且必填为“是”时，必须提供该键。",
        "位置/长度通常使用图纸单位；工程模型固定毫米，纸空间固定毫米，角度按字段说明。具体前置条件见[工具契约](../skills/cad-mcp/references/tool-contracts.md)。", "",
        "## 返回与错误", "",
        "多数成功结果是含 `ok=true` 的 JSON 文字；`cad_get_drawing_info`、`cad_list_entities`、`cad_check_drawing` 成功时为纯文本。`cad_preview_region` 返回标准 MCP 内容块。",
        "工具捕获的失败返回 `ok=false`、`error`、`error_detail`；SDK 参数校验也可能返回协议级错误。不能对所有成功文字无条件执行 JSON 解析。",
        "下列“外层返回键”只列入口明确写出的键，不是完整输出 Schema；后端可增加业务字段，`ok=true` 也不等于 `verified=true`、`pass=true` 或已经保存。", "",
        "## 工具索引", "", "| 工具 | 用途 | 模式 |", "|---|---|---|"]
    for name, tool in sorted(tools.items()):
        if not tool.description.strip():
            raise ValueError(f"工具缺少说明: {name}")
        lines.append(f"| [{name}](#{name}) | {clean_cell(tool.description.splitlines()[0])} | {mode(name)} |")
    descriptors = []
    for name, tool in sorted(tools.items()):
        short = name.removeprefix("cad_")
        p = parameter_schema(tool)
        props = p.get("properties", {})
        required = p.get("required", [])
        source = Path(inspect.getsourcefile(inspect.unwrap(tool.fn))).relative_to(ROOT).as_posix()
        readonly = tool.annotations is not None and tool.annotations.readOnlyHint is True
        lines += ["", f"## {name}", "", tool.description.splitlines()[0], "",
            f"模式：{mode(name)}。声明：{'只读' if readonly else '会改变状态、图纸或文件'}。入口：[源码](../{source})。"]
        if short in NOTES:
            lines += ["", NOTES[short]]
        if short in TEXT_RESULTS:
            result = "成功为纯文本，无 `ok=true` 包装；失败仍使用结构化错误。"
        elif short == "preview_region":
            result = "MCP CallToolResult：JSON 文字含 image_path、image_included、warnings，可附 image/png 内容块。"
        else:
            keys = returned_fields(tool.fn)
            result = "成功为 JSON。外层返回键：" + ("、".join(f"`{k}`" for k in keys) if keys else "由运行时结果提供") + "；其余业务字段见工具契约及实际回读。"
        lines += ["", "返回：" + result, ""]
        if props:
            lines += ["| params 字段 | 必填 | 类型与约束 | 默认值 | 含义 |", "|---|---|---|---|---|"]
            for key, schema in props.items():
                if not schema.get("description"):
                    raise ValueError(f"参数缺少说明: {name}.{key}")
                detail = {k: v for k, v in schema.items() if k not in {"description", "title", "default"}}
                default = json.dumps(schema["default"], ensure_ascii=False) if "default" in schema else "未设默认值"
                lines.append(f"| `{key}` | {'是' if key in required else '否'} | `{clean_cell(json.dumps(detail, ensure_ascii=False, separators=(',', ':')))}` | {clean_cell(default)} | {clean_cell(schema['description'])} |")
        else:
            lines.append("参数：`params={}`，无业务字段。")
        descriptors.append(server._tool_descriptor(tool))
    return {
        ROOT / "docs/api-reference.md": "\n".join(lines) + "\n",
        ROOT / "docs/tool-schemas.json": json.dumps({"tool_count": len(tools), "tools": descriptors}, ensure_ascii=False, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只检查生成文档是否与运行时一致")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="cad-mcp-tool-docs-") as scratch, ExitStack() as cleanup:
        # Windows cannot remove a log file while its FileHandler is open.
        # ExitStack runs before TemporaryDirectory, including on import failure.
        cleanup.callback(logging.shutdown)
        os.environ.update(CAD_MODE="dxf", CAD_SEMANTIC_POLICY="strict", CAD_MCP_TOOLSET="all",
            CAD_CONFIG_FILE=str(Path(scratch) / "absent-config.json"),
            CAD_DRAWINGS_DIR=str(Path(scratch) / "drawings"), CAD_LOG_DIR=str(Path(scratch) / "logs"))
        sys.path.insert(0, str(ROOT / "src"))
        from cad_mcp import server
        outputs = render(server)
        stale = []
        for path, text in outputs.items():
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.write_bytes(text.encode("utf-8"))
        if stale:
            print("需更新: " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"{'已核对' if args.check else '已生成'} {len(server._FULL_TOOL_REGISTRY)} 个工具的参考及完整参数结构；未连接 CAD。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
